// Where a document's content comes from at the source points of a space which has a sourced
// axis: what the commit which a value of that axis stands for has at the document's path, as
// lines, or `Unset` if it has nothing there. The engine reads nothing itself; whatever opens
// a store gives each dossier its source. What a source gives for a value must never change.
trait Source:
  def content(value: Text): Optional[List[Text]] raises Axis.Error
